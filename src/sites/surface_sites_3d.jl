# Sites on both sides of triangulated surfaces in 3D (UPR: surfaceSites3D,
# ballInt, removeSurfaceConflictSites3D). A ball is centered at each vertex
# of the surface triangulation; the three balls of a triangle intersect in two
# points, one on each side of the triangle, which become sites. At free edges
# of a surface (edges of only one triangle) a tip site is placed on the
# intersection circle of the two balls, in the plane of the triangle and
# pointing away from it, so the conforming faces stop at the edge (the 3D
# analogue of the tips in surface_sites_2d, which UPR does not have).

"""
    SurfaceSites3D

Sites generated by [`surface_sites_3d`](@ref).

# Fields
- `sites`: site coordinates.
- `spacing`: distance from the site to the plane of its triangle.
- `generators`: for each site, the `(triangle, side)` pairs that generated it
  (triangles are numbered globally over all surfaces).
- `site_surface`: surface index of each site.
- `centers`, `radii`, `center_surface`: the balls and their surface index.
- `triangle_surface`: surface index of each triangle.
- `tips`, `tip_surface`: sites beyond the free edges of the surfaces and
  their surface index.
"""
struct SurfaceSites3D
    sites::Vector{Vec3}
    spacing::Vector{Float64}
    generators::Vector{Vector{Tuple{Int, Int}}}
    site_surface::Vector{Int}
    centers::Vector{Vec3}
    radii::Vector{Float64}
    center_surface::Vector{Int}
    triangle_surface::Vector{Int}
    tips::Vector{Vec3}
    tip_surface::Vector{Int}
end

function Base.show(io::IO, F::SurfaceSites3D)
    print(io, "SurfaceSites3D with $(length(F.sites)) sites on $(length(unique(F.triangle_surface))) surfaces and $(length(F.tips)) tips")
end

function _to_triangulation(s)
    if s isa NamedTuple
        pts, tri = s.points, s.triangles
    else
        pts, tri = s
    end
    pts = to_points(pts, 3)
    if tri isa AbstractMatrix
        size(tri, 2) == 3 || (tri = permutedims(tri))
        tri = [(Int(tri[i, 1]), Int(tri[i, 2]), Int(tri[i, 3])) for i in axes(tri, 1)]
    else
        tri = [(Int(t[1]), Int(t[2]), Int(t[3])) for t in tri]
    end
    return pts, tri
end

"""
    ball_intersection(c1, r1, c2, r2, c3, r3)

The two intersection points of three spheres, `(top, bottom, offset)` where
`offset` is the distance from the points to the plane through the centers.
`top` lies on the side of the right-hand normal of `(c1, c2, c3)`. Returns
`nothing` if the spheres do not intersect.
"""
function ball_intersection(c1::Vec3, r1, c2::Vec3, r2, c3::Vec3, r3)
    p1 = c2 - c1
    dx = norm(p1)
    nx = p1 / dx
    p2 = c3 - c1
    midx = dot(nx, p2)
    ny = p2 - midx * nx
    norm(ny) > 1e-12 * dx || return nothing # degenerate triangle
    ny = ny / norm(ny)
    nz = cross(nx, ny)
    X = (dx^2 - r2^2 + r1^2) / (2 * dx)
    midy = dot(ny, p2)
    Y = (r1^2 - r3^2 + midy^2 + midx^2) / (2 * midy) - midx / midy * X
    Z2 = r1^2 - X^2 - Y^2
    Z2 >= 0 || return nothing
    Z = sqrt(Z2)
    base = c1 + X * nx + Y * ny
    return base + Z * nz, base - Z * nz, Z
end

"""
    edge_tip(a, Ra, b, Rb, c, Rc; valid = (p, r) -> true)

Tip site for the free edge `(a, b)` of the triangle `(a, b, c)` with balls of
radii `Ra`, `Rb`, `Rc`. The tip lies on the intersection circle of the balls
at `a` and `b`, so the bisectors between the tip and the two sites of the
triangle pass through the edge. It is placed in the plane of the triangle, on
the opposite side of the edge from `c`. If `valid(p, r)` is false for this
point (`r` is the circle radius), the tip is rotated along the circle towards
the sites of the triangle, staying within the outer three quarters of the arc
between them. Returns `nothing` if no valid point is found or the balls do
not intersect.
"""
function edge_tip(a::Vec3, Ra, b::Vec3, Rb, c::Vec3, Rc; valid = (p, r) -> true)
    tb = ball_intersection(a, Ra, b, Rb, c, Rc)
    isnothing(tb) && return nothing
    d = norm(b - a)
    e = (b - a) / d
    X = (d^2 - Rb^2 + Ra^2) / (2 * d)
    r2 = Ra^2 - X^2
    r2 > 0 || return nothing
    r = sqrt(r2)
    m = a + X * e
    t = a - c
    t = t - dot(t, e) * e
    t = t / norm(t)
    u = cross(e, t)
    angle(p) = atan(dot(p - m, u), dot(p - m, t))
    # The triangle sites are on the circle, one on each side of the plane
    lim = sort([angle(tb[1]), angle(tb[2])])
    lim[1] < 0 < lim[2] || return nothing
    tip(θ) = m + r * (cos(θ) * t + sin(θ) * u)
    dθ = pi / 72
    for k in 0:72, θ in (k * dθ, -k * dθ)
        0.75 * lim[1] <= θ <= 0.75 * lim[2] || continue
        p = tip(θ)
        valid(p, r) && return p
    end
    return nothing
end

"""
    surface_sites_3d(surfaces, rho; tips = true, domain = nothing)

Create sites on both sides of triangulated surfaces (UPR: `surfaceSites3D`).
Each surface is given as `(points, triangles)` (or a named tuple with these
fields). `rho` gives the ball radius at the surface vertices: a number, a
function of position, or a vector with one per surface. The radius should be
larger than the circumradius of the triangles (about the edge length works
well for regular triangulations).

If `tips` is true, a tip site is placed beyond each free edge (an edge of only
one triangle), see [`edge_tip`](@ref), so that the conforming faces stop at
the edge. Tips are kept outside all balls, and if a `domain` is given,
inside it; edges on the domain boundary get no tip.
"""
function surface_sites_3d(surfaces, rho; tips = true, domain = nothing)
    surfaces = surfaces isa Union{Tuple, NamedTuple} ? [surfaces] : surfaces
    ns = length(surfaces)
    rho = rho isa AbstractVector ? _per_line(rho, ns) : fill(rho, ns)
    raw = Vec3[]
    raw_tri = Int[]
    raw_side = Int[]
    raw_offset = Float64[]
    centers = Vec3[]
    radii = Float64[]
    center_surface = Int[]
    triangle_surface = Int[]
    tip_input = []
    ntri = 0
    nfail = 0
    for (i, s) in enumerate(surfaces)
        pts, tris = _to_triangulation(s)
        R = [_eval_size(rho[i], p) for p in pts]
        used = falses(length(pts))
        for t in tris
            ntri += 1
            push!(triangle_surface, i)
            a, b, c = t
            used[a] = used[b] = used[c] = true
            r = ball_intersection(pts[a], R[a], pts[b], R[b], pts[c], R[c])
            if isnothing(r)
                nfail += 1
                continue
            end
            top, bot, Z = r
            push!(raw, top); push!(raw_tri, ntri); push!(raw_side, 1); push!(raw_offset, Z)
            push!(raw, bot); push!(raw_tri, ntri); push!(raw_side, -1); push!(raw_offset, Z)
        end
        tips && push!(tip_input, (i, pts, tris, R))
        append!(centers, pts[used])
        append!(radii, R[used])
        append!(center_surface, fill(i, count(used)))
    end
    if nfail > 0
        @warn "$nfail surface triangles have no ball intersection; increase rho"
    end
    L = 1.0
    if !isempty(centers)
        lo, hi = bounding_box(centers)
        L = norm(hi - lo)
    end
    sites, smap = unique_points(raw; tol = 1e-12 * L)
    generators = [Tuple{Int, Int}[] for _ in sites]
    spacing = fill(Inf, length(sites))
    site_surface = zeros(Int, length(sites))
    for (k, s) in enumerate(smap)
        push!(generators[s], (raw_tri[k], raw_side[k]))
        spacing[s] = min(spacing[s], raw_offset[k])
        site_surface[s] = triangle_surface[raw_tri[k]]
    end
    tip_pts, tip_surface = _surface_tips(tip_input, centers, radii, domain)
    if !isempty(tip_pts)
        tip_pts, tmap = unique_points(tip_pts; tol = 1e-12 * L)
        tip_surface = [tip_surface[findfirst(==(k), tmap)] for k in eachindex(tip_pts)]
    end
    return SurfaceSites3D(sites, spacing, generators, site_surface, centers, radii, center_surface, triangle_surface,
        tip_pts, tip_surface)
end

# Tip sites at the free edges of the surfaces, outside all balls (sites on a
# sphere are allowed) and inside the domain
function _surface_tips(input, centers, radii, domain)
    tip_pts = Vec3[]
    tip_surface = Int[]
    isempty(input) && return tip_pts, tip_surface
    tree = KDTree(centers)
    Rmax = maximum(radii)
    function valid(p, r)
        isnothing(domain) || inside(domain, p; tol = -0.1 * r) || return false
        for k in inrange(tree, p, Rmax)
            norm(p - centers[k]) < radii[k] * (1 - 1e-9) && return false
        end
        return true
    end
    for (i, pts, tris, R) in input
        for (a, b, c) in _free_edges(tris)
            isnothing(domain) || _on_domain_boundary(domain, pts[a], pts[b]) && continue
            p = edge_tip(pts[a], R[a], pts[b], R[b], pts[c], R[c]; valid = valid)
            isnothing(p) && continue
            push!(tip_pts, p)
            push!(tip_surface, i)
        end
    end
    return tip_pts, tip_surface
end

# Edges `(a, b, c)` used by only one triangle `(a, b, c)` (in any order)
function _free_edges(tris)
    count = Dict{Tuple{Int, Int}, Int}()
    for (a, b, c) in tris, (p, q) in ((a, b), (b, c), (c, a))
        k = minmax(p, q)
        count[k] = get(count, k, 0) + 1
    end
    free = NTuple{3, Int}[]
    for (a, b, c) in tris, (p, q, r) in ((a, b, c), (b, c, a), (c, a, b))
        count[minmax(p, q)] == 1 && push!(free, (p, q, r))
    end
    return free
end

# Both end points on the same facet of the domain
function _on_domain_boundary(d::ConvexPolyhedronDomain, a, b)
    tol = 1e-10 * domain_diameter(d)
    return any(abs(dot(n, a) - o) < tol && abs(dot(n, b) - o) < tol for (n, o) in zip(d.normals, d.offsets))
end

"""
    remove_surface_conflict_sites_3d(F)

Remove sites of surface `j` that lie inside the balls of a surface `i < j`
(UPR: `removeSurfaceConflictSites3D`). Surfaces given first thus have
priority at intersections.
"""
function remove_surface_conflict_sites_3d(F::SurfaceSites3D)
    removed = falses(length(F.sites))
    ns = isempty(F.triangle_surface) ? 0 : maximum(F.triangle_surface)
    for i in 1:ns
        later = findall(s -> s > i, F.site_surface)
        isempty(later) && continue
        balls = findall(==(i), F.center_surface)
        _, rem = surface_sufficient_condition(F.sites[later], F.centers[balls], F.radii[balls])
        removed[later[rem]] .= true
    end
    keep = .!removed
    return SurfaceSites3D(F.sites[keep], F.spacing[keep], F.generators[keep], F.site_surface[keep],
        F.centers, F.radii, F.center_surface, F.triangle_surface, F.tips, F.tip_surface)
end

"""
    surface_face_tag(F::SurfaceSites3D, i, j)

Surface index of the face between sites `i` and `j` of `F` if they were
generated by the same triangle on opposite sides, `0` otherwise.
"""
function surface_face_tag(F::SurfaceSites3D, i::Int, j::Int)
    for (t, s) in F.generators[i]
        if (t, -s) in F.generators[j]
            return F.triangle_surface[t]
        end
    end
    return 0
end
