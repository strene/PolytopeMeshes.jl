# Sites on both sides of 2D face constraints (faults/fractures) such that the
# Voronoi faces trace the constraints (UPR: surfaceSites2D).
#
# Each constraint is covered by a chain of circles. Two consecutive circles
# (an "edge" of the circle graph) intersect in two points, one on each side of
# the constraint; these are the sites. The Voronoi face between the two sites
# of an edge is the segment between the circle centers, provided no other
# site lies inside the circles. At intersections between constraints the
# circles are shared, and circles that contain sites from other branches are
# shrunk or merged (UPR: fixIntersections/mergeCirc).

"""
    SurfaceSites2D

Sites generated by [`surface_sites_2d`](@ref).

# Fields
- `sites`: site coordinates.
- `spacing`: distance between the site and its partner across the constraint.
- `generators`: for each site, the circle-graph edges `(edge, side)` that
  generated it (`side = 1` left, `-1` right of the edge direction).
- `centers`, `radii`: circles. Background sites inside these must be removed.
- `edges`: circle pairs generating sites.
- `edge_constraint`: face constraint index of each edge.
- `edge_crossing`: index of the cell constraint crossing the edge (`0` if
  none). Sites of such edges represent the cell constraint at the crossing.
- `tips`: sites placed beyond the free ends of the constraints.
"""
struct SurfaceSites2D
    sites::Vector{Vec2}
    spacing::Vector{Float64}
    generators::Vector{Vector{Tuple{Int, Int}}}
    centers::Vector{Vec2}
    radii::Vector{Float64}
    edges::Vector{Tuple{Int, Int}}
    edge_constraint::Vector{Int}
    edge_crossing::Vector{Int}
    tips::Vector{Vec2}
end

function Base.show(io::IO, F::SurfaceSites2D)
    print(io, "SurfaceSites2D with $(length(F.sites)) sites, $(length(F.centers)) circles and $(length(F.tips)) tips")
end

"""
    surface_sites_2d(face_constraints, ds; kwarg...)

Create sites on both sides of the polylines `face_constraints` so that the
faces of the Voronoi diagram conform to them (UPR: `surfaceSites2D`). The
constraints are split at their mutual intersections and at intersections with
`cell_constraints`.

# Keyword arguments
- `fh = ds`: spacing of the circle centers along the constraints, a number or
  a function of position.
- `circle_factor = 0.6`: ratio between circle radius and the distance between
  circle centers, in `(0.5, 1)`. Small values place the sites close to the
  constraints.
- `interpolate = false`: per constraint; if `false` the polyline vertices are
  circle centers, otherwise the centers are interpolated along the curve.
- `cell_constraints = []`: polylines of cell constraints crossing the face
  constraints.
- `max_iterations = 20`: iterations used to resolve conflicts at
  intersections.
"""
function surface_sites_2d(face_constraints, ds; fh = ds, circle_factor = 0.6, interpolate = false,
        cell_constraints = Vector{Vec2}[], max_iterations = 20, merge_tol = 0.0)
    0.5 < circle_factor < 1 || throw(ArgumentError("circle_factor must be in (0.5, 1)"))
    fc = to_polylines(face_constraints, 2)
    cc = filter(l -> length(l) > 1, to_polylines(cell_constraints, 2))
    cc_index = findall(l -> length(l) > 1, to_polylines(cell_constraints, 2))
    interpolate = _per_line(interpolate, length(fc))
    split = split_at_intersections(fc, cc)
    cf = circle_factor
    centers = Vec2[]
    radii = Float64[]
    edges = Tuple{Int, Int}[]
    edge_constraint = Int[]
    edge_crossing = Int[]
    tips = Vec2[]
    npieces = length(split.lines)
    first_circle = zeros(Int, npieces)
    last_circle = zeros(Int, npieces)
    for i in 1:npieces
        line = split.lines[i]
        length(line) < 2 && continue
        fcut = split.self_cut[i]
        ccut = split.other_cut[i]
        se = (ccut in (2, 3) ? 0.5 : 0.0, ccut in (1, 3) ? 0.5 : 0.0)
        c = interpolate_line_path(line, fh, ds; se = se, interpolate = interpolate[split.origin[i]])
        m = length(c)
        m < 2 && continue
        if m == 2 && norm(c[2] - c[1]) < 0.8 * _eval_size(fh, (c[1] + c[2]) / 2)
            continue
        end
        L = [norm(c[k + 1] - c[k]) for k in 1:(m - 1)]
        R = cf .* vcat(L[1], [(L[k] + L[k + 1]) / 2 for k in 1:(m - 2)], L[end])
        if fcut in (1, 3)
            R[end] = _eval_size(fh, c[end]) * cf
        end
        if fcut in (2, 3)
            R[1] = _eval_size(fh, c[1]) * cf
        end
        offset = length(centers)
        append!(centers, c)
        append!(radii, R)
        for k in 1:(m - 1)
            push!(edges, (offset + k, offset + k + 1))
            push!(edge_constraint, split.origin[i])
            push!(edge_crossing, 0)
        end
        first_circle[i] = offset + 1
        last_circle[i] = offset + m
        # Tip sites at free ends
        if !(fcut in (1, 3)) && !(ccut in (1, 3))
            t = c[end] - c[end - 1]
            push!(tips, c[end] + t / norm(t) * R[end])
        end
        if !(fcut in (2, 3)) && !(ccut in (2, 3))
            t = c[1] - c[2]
            push!(tips, c[1] + t / norm(t) * R[1])
        end
    end
    # Connect the pieces on both sides of a cell constraint crossing
    for i in 1:(npieces - 1)
        if split.origin[i] == split.origin[i + 1] && split.other_cut[i] in (1, 3) && split.other_cut[i + 1] in (2, 3)
            a, b = last_circle[i], first_circle[i + 1]
            (a == 0 || b == 0) && continue
            push!(edges, (a, b))
            push!(edge_constraint, split.origin[i])
            k = split.other_end[i]
            push!(edge_crossing, k > 0 ? cc_index[k] : 0)
        end
    end
    # Merge circles with the same center (intersections between constraints)
    ctol = 1e-9 * Float64(ds)
    ucenters, cmap = unique_points(centers; tol = ctol)
    uradii = zeros(length(ucenters))
    seen = falses(length(ucenters))
    for (i, k) in enumerate(cmap)
        if !seen[k]
            uradii[k] = radii[i]
            seen[k] = true
        end
    end
    edges = [(cmap[a], cmap[b]) for (a, b) in edges]
    centers, radii = ucenters, uradii
    edges, edge_constraint, edge_crossing = _clean_edges(edges, edge_constraint, edge_crossing)
    # Resolve conflicts at intersections
    centers, radii, edges, edge_constraint, edge_crossing = _fix_intersections(
        centers, radii, edges, edge_constraint, edge_crossing, fh, cf, max_iterations, merge_tol)
    # Final sites
    raw, raw_edge, raw_side, valid = _edge_sites(centers, radii, edges)
    if !all(valid)
        @warn "$(count(!, valid) ÷ 2) circle pairs do not intersect; conformity is not guaranteed there"
    end
    raw = raw[valid]
    raw_edge = raw_edge[valid]
    raw_side = raw_side[valid]
    sites, smap = unique_points(raw; tol = ctol)
    generators = [Tuple{Int, Int}[] for _ in sites]
    spacing = fill(Inf, length(sites))
    for (k, s) in enumerate(smap)
        push!(generators[s], (raw_edge[k], raw_side[k]))
    end
    # Distance between the two sites of each edge
    edge_pts = Dict{Int, Vector{Vec2}}()
    for k in eachindex(raw)
        push!(get!(Vector{Vec2}, edge_pts, raw_edge[k]), raw[k])
    end
    for (k, s) in enumerate(smap)
        p = edge_pts[raw_edge[k]]
        if length(p) == 2
            spacing[s] = min(spacing[s], norm(p[1] - p[2]))
        end
    end
    spacing[.!isfinite.(spacing)] .= Float64(ds)
    # Remove circles that no longer generate any sites
    used = falses(length(centers))
    for (a, b) in edges
        used[a] = true
        used[b] = true
    end
    newid = cumsum(used)
    edges = [(newid[a], newid[b]) for (a, b) in edges]
    return SurfaceSites2D(sites, spacing, generators, centers[used], radii[used], edges,
        edge_constraint, edge_crossing, tips)
end

function _clean_edges(edges, edge_constraint, edge_crossing)
    seen = Dict{Tuple{Int, Int}, Int}()
    E = Tuple{Int, Int}[]
    C = Int[]
    X = Int[]
    for (k, (a, b)) in enumerate(edges)
        a == b && continue
        key = minmax(a, b)
        if haskey(seen, key)
            # Keep crossing information if any of the duplicates has it
            if edge_crossing[k] != 0
                X[seen[key]] = edge_crossing[k]
            end
            continue
        end
        push!(E, (a, b))
        push!(C, edge_constraint[k])
        push!(X, edge_crossing[k])
        seen[key] = length(E)
    end
    return E, C, X
end

# Intersection points of two circles, (right, left) relative to the direction
# from the first to the second center.
function _circle_intersection(c1::Vec2, r1, c2::Vec2, r2)
    v = c2 - c1
    d = norm(v)
    a = (d^2 - r2^2 + r1^2) / (2 * d)
    h2 = r1^2 - a^2
    valid = d > 0 && h2 >= 0
    h = sqrt(max(h2, 0.0))
    n1 = v / d
    n2 = Vec2(-n1[2], n1[1])
    base = c1 + a * n1
    return base - h * n2, base + h * n2, valid
end

function _edge_sites(centers, radii, edges)
    raw = Vec2[]
    raw_edge = Int[]
    raw_side = Int[]
    valid = Bool[]
    for (e, (a, b)) in enumerate(edges)
        right, left, ok = _circle_intersection(centers[a], radii[a], centers[b], radii[b])
        push!(raw, right); push!(raw_edge, e); push!(raw_side, -1); push!(valid, ok)
        push!(raw, left); push!(raw_edge, e); push!(raw_side, 1); push!(valid, ok)
    end
    return raw, raw_edge, raw_side, valid
end

function _edge_valid(centers, radii, a, b)
    d = norm(centers[b] - centers[a])
    return abs(radii[a] - radii[b]) <= d <= radii[a] + radii[b]
end

function _fix_intersections(centers, radii, edges, edge_constraint, edge_crossing, fh, cf, max_iterations, merge_tol)
    centers = copy(centers)
    radii = copy(radii)
    unresolved = 0
    for it in 1:max_iterations
        nbrs = [Set{Int}() for _ in centers]
        for (a, b) in edges
            push!(nbrs[a], b)
            push!(nbrs[b], a)
        end
        raw, raw_edge, _, valid = _edge_sites(centers, radii, edges)
        pts = raw[valid]
        isempty(pts) && break
        pedge = raw_edge[valid]
        tree = KDTree(pts)
        triples = Set{Tuple{Int, Int, Int}}()
        unresolved = 0
        for c in eachindex(centers)
            isempty(nbrs[c]) && continue
            R = radii[c] * (1 - 1e-10)
            for s in inrange(tree, centers[c], R)
                a, b = edges[pedge[s]]
                (c == a || c == b) && continue
                X = a in nbrs[c] ? a : (b in nbrs[c] ? b : 0)
                if X == 0
                    unresolved += 1
                    continue
                end
                other = X == a ? b : a
                other == c && continue
                push!(triples, (min(c, other), max(c, other), X))
            end
        end
        isempty(triples) && break
        # Merge circles that are (almost) at the same place
        to_merge = Tuple{Int, Int}[]
        for (c, o, X) in triples
            if norm(centers[c] - centers[o]) < merge_tol * _eval_size(fh, centers[c])
                push!(to_merge, (c, o))
            end
        end
        if isempty(to_merge)
            old = copy(radii)
            for (c, o, X) in triples
                dir = (centers[c] + centers[o]) / 2 - centers[X]
                nd = norm(dir)
                nd == 0 && continue
                p = centers[X] + radii[X] * dir / nd
                radii[c] = min(radii[c], norm(centers[c] - p))
                radii[o] = min(radii[o], norm(centers[o] - p))
            end
            for (c, o, X) in triples
                ok = true
                for q in (c, o), r in nbrs[q]
                    ok &= _edge_valid(centers, radii, q, r)
                end
                ok || push!(to_merge, (c, o))
            end
            if isempty(to_merge)
                continue
            end
            radii = old
        end
        # Merge pairs of circles into a single circle
        merged = Set{Int}()
        for (c, o) in to_merge
            (c in merged || o in merged) && continue
            push!(merged, c); push!(merged, o)
            push!(centers, (centers[c] + centers[o]) / 2)
            push!(radii, 1.1 * cf * _eval_size(fh, centers[c]))
            M = length(centers)
            edges = [((a == c || a == o) ? M : a, (b == c || b == o) ? M : b) for (a, b) in edges]
        end
        edges, edge_constraint, edge_crossing = _clean_edges(edges, edge_constraint, edge_crossing)
    end
    if unresolved > 0
        @warn "$unresolved face constraint sites lie inside circles of other constraints; conformity is not guaranteed there"
    end
    return centers, radii, edges, edge_constraint, edge_crossing
end

"""
    surface_face_tag(F, i, j)

Face constraint index of the Voronoi face between sites `i` and `j` of `F`, or
`0` if the face does not lie on a face constraint.
"""
function surface_face_tag(F::SurfaceSites2D, i::Int, j::Int)
    for (e, s) in F.generators[i]
        if (e, -s) in F.generators[j]
            return F.edge_constraint[e]
        end
    end
    return 0
end

"""
    crossing_cell_tags(F)

Cell constraint index for each site of `F` that represents a cell constraint
crossing a face constraint (`0` otherwise).
"""
function crossing_cell_tags(F::SurfaceSites2D)
    tags = zeros(Int, length(F.sites))
    for (s, gen) in enumerate(F.generators)
        for (e, _) in gen
            if F.edge_crossing[e] != 0
                tags[s] = F.edge_crossing[e]
            end
        end
    end
    return tags
end
